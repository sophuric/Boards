package me.sophur.boards.datagen;

import me.sophur.boards.BoardsBlocks;
import net.fabricmc.fabric.api.datagen.v1.FabricPackOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.FabricBlockLootSubProvider;
import net.minecraft.core.HolderLookup;

import java.util.concurrent.CompletableFuture;

public class BoardsBlockLootTableProvider extends FabricBlockLootSubProvider {
    protected BoardsBlockLootTableProvider(FabricPackOutput output, CompletableFuture<HolderLookup.Provider> registriesFuture) {
        super(output, registriesFuture);
    }

    @Override
    public void generate() {
        dropSelf(BoardsBlocks.FRAME_BLOCK);
    }
}
